export function localizeChatSubagentStatus(text: string): string {
  const formatted =
    /^(Starting|Idle|Working|Waiting|Completed|Interrupted|Failed|Cancelled)( in)?(.*)$/.exec(text);
  return formatted
    ? `${localizeChatText(formatted[1]!)}${formatted[2] ? " · 소요 시간:" : ""}${formatted[3]}`
    : text;
}
export function localizeChatCompactionLabel(text: string): string {
  const counts = /^Context compacted (.+) → (.+) tokens$/.exec(text);
  return counts ? `대화 기록 요약: ${counts[1]} → ${counts[2]}토큰` : localizeChatText(text);
}

export function localizeApprovalOptionLabel(label: string): string {
  const translated = localizeChatText(label);
  if (translated !== label) return translated;
  const named = /^Always allow (.+)$/.exec(label);
  return named ? `${named[1]} 항상 허용` : label;
}
